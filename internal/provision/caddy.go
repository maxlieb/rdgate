// Caddy is the single public listener. Both services sit behind it.
//
// It was added to solve two problems at once. Funnel only offers ports 443,
// 8443 and 10000, and the earlier design spent two of them - which works on an
// open network and fails on a managed one that permits only outbound 443. And
// serving your own domain needs certificate issuance and renewal, which Caddy
// does without being asked.
//
// RD Gateway's non-standard verbs (RDG_IN_DATA / RDG_OUT_DATA) pass through
// fine: Caddy reverse-proxies by path and host without caring about methods.
type Caddy struct {
	Exe       string
	Dir       string
	Caddyfile string
}

func NewCaddy(c Config) Caddy {
	dir := winJoin(c.InstallRoot, "caddy")
	return Caddy{
		Exe:       winJoin(dir, "caddy.exe"),
		Dir:       dir,
		Caddyfile: winJoin(dir, "Caddyfile"),
	}
}

func (cd Caddy) DownloadURL(version string) string {
	return fmt.Sprintf(
		"https://github.com/caddyserver/caddy/releases/download/v%s/caddy_%s_windows_amd64.zip",
		version, version)
}

// EnsureBinary fetches caddy.exe out of the official release archive.
func (cd Caddy) EnsureBinary(ctx context.Context, version string, report Reporter) error {
	if fi, err := os.Stat(cd.Exe); err == nil && fi.Size() > 0 {
		report.step("Web front end", StepSkipped, "already downloaded")
		return nil
	}
	if err := os.MkdirAll(cd.Dir, 0o700); err != nil {
		return err
	}

	report.step("Web front end", StepRunning, "downloading Caddy "+version)
	tmpZip := cd.Exe + ".zip"
	if _, err := downloadTo(ctx, cd.DownloadURL(version), tmpZip); err != nil {
		_ = os.Remove(tmpZip)
		return fmt.Errorf("downloading Caddy: %w", err)
	}
	defer os.Remove(tmpZip)

	if err := extractOne(tmpZip, "caddy.exe", cd.Exe); err != nil {
		return err
	}
	report.step("Web front end", StepDone, "downloaded")
	return nil
}

func extractOne(archivePath, want, dest string) error {
	zr, err := zip.OpenReader(archivePath)
	if err != nil {
		return err
	}
	defer zr.Close()

	for _, f := range zr.File {
		// Compare the base name only, and never join the archive's path onto
		// a directory: a crafted archive with ../ in its names would
		// otherwise write outside the install root.
		if !strings.EqualFold(baseName(f.Name), want) {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return err
		}
		defer rc.Close()

		out, err := os.OpenFile(dest, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o700)
		if err != nil {
			return err
		}
		defer out.Close()

		if _, err := io.Copy(out, io.LimitReader(rc, 256<<20)); err != nil {
			return err
		}
		return nil
	}
	return errors.New(want + " was not found in the downloaded archive")
}

func baseName(p string) string {
	p = strings.ReplaceAll(p, "\\", "/")
	if i := strings.LastIndexByte(p, '/'); i >= 0 {
		return p[i+1:]
	}
	return p
}

// Caddyfile renders the configuration for whichever front door is in use.
//
// The routing is identical in all three: sign-in under /auth, the gateway
// everywhere else. Only the listener differs - who terminates TLS, and which
// interface the port is bound to.
func Caddyfile(c Config) (string, error) {
	rdpgw := fmt.Sprintf("127.0.0.1:%d", c.RdpgwPort)
	gitea := fmt.Sprintf("127.0.0.1:%d", c.GiteaPort)

	// flush_interval -1 matters for RD Gateway: the outbound channel is one
	// long response that must be forwarded as bytes arrive, not buffered.
	routes := "\thandle_path " + AuthPath + "/* {\n" +
		"\t\treverse_proxy " + gitea + "\n" +
		"\t}\n" +
		"\thandle {\n" +
		"\t\treverse_proxy " + rdpgw + " {\n" +
		"\t\t\tflush_interval -1\n" +
		"\t\t}\n" +
		"\t}\n"

	var b strings.Builder
	b.WriteString("# Generated by RD Gateway Manager. Edits are overwritten.\n")
	b.WriteString("{\n")
	b.WriteString("\tadmin off\n") // nothing should be able to reconfigure this at runtime

	switch c.FrontDoor {
	case FrontDoorDirect:
		if c.PublicDomain == "" {
			return "", errors.New("direct mode needs a hostname for the gateway")
		}
		if _, err := NormalizeHost(c.PublicDomain); err != nil {
			return "", err
		}
		if err := validateEmail(c.ACMEEmail); err != nil {
			return "", err
		}
		if c.ACMEEmail != "" {
			b.WriteString("\temail " + c.ACMEEmail + "\n")
		}
		b.WriteString("}\n\n")
		// Caddy obtains and renews the certificate on its own.
		b.WriteString(c.PublicDomain + " {\n" + routes + "}\n")

	case FrontDoorRelay:
		if c.TailscaleIP == "" {
			return "", errors.New("relay mode needs this machine's Tailscale address")
		}
		// TLS ends on the relay, which holds the certificate. Here the traffic
		// arrives as plain HTTP over the tailnet, and this listener is bound
		// to the tailnet address alone: it is not on the LAN, and not on the
		// internet.
		b.WriteString("\tauto_https off\n")
		b.WriteString("}\n\n")
		b.WriteString(fmt.Sprintf("http://:%d {\n", c.CaddyPort))
		b.WriteString("\tbind " + c.TailscaleIP + "\n")
		b.WriteString(routes + "}\n")

	default: // funnel
		// Tailscale has already terminated TLS and hands us plain HTTP on
		// loopback, so Caddy must not try to obtain a certificate of its own.
		b.WriteString("\tauto_https off\n")
		b.WriteString("}\n\n")
		b.WriteString(fmt.Sprintf("http://:%d {\n", c.CaddyPort))
		b.WriteString("\tbind 127.0.0.1\n")
		b.WriteString(routes + "}\n")
	}
	return b.String(), nil
}

// WriteConfig renders and writes the Caddyfile.
func (cd Caddy) WriteConfig(c Config) error {
	if err := os.MkdirAll(cd.Dir, 0o700); err != nil {
		return err
	}
	body, err := Caddyfile(c)
	if err != nil {
		return err
	}
	return os.WriteFile(cd.Caddyfile, []byte(body), 0o600)
}

// ListenPort is where Caddy accepts connections for this configuration.
func (c Config) CaddyListenPort() int {
	if c.FrontDoor == FrontDoorDirect {
		return PublicPort
	}
	return c.CaddyPort
}
